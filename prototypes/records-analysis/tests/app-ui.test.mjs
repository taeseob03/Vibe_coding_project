import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';

test('app flow: swipe, nickname search, pending invitation, acceptance, inbox, posting and retry',async()=>{
  const html=await readFile(new URL('../static/index.html',import.meta.url),'utf8');
  const dom=new JSDOM(html,{url:'http://localhost/'}),win=dom.window;
  for(const key of ['window','document','navigator','location','localStorage','FormData'])Object.defineProperty(globalThis,key,{value:key==='window'?win:win[key],configurable:true});
  globalThis.requestAnimationFrame=()=>1;globalThis.cancelAnimationFrame=()=>{};
  win.HTMLCanvasElement.prototype.getContext=()=>({});
  win.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  win.HTMLDialogElement.prototype.close=function(){this.open=false;};
  URL.createObjectURL=()=> 'blob:test-photo';URL.revokeObjectURL=()=>{};
  const $=selector=>win.document.querySelector(selector);
  const until=async predicate=>{for(let i=0;i<100;i++){if(predicate())return;await new Promise(resolve=>setTimeout(resolve,5));}throw new Error('UI did not reach expected state');};
  const counts=count=>['술','공부','연애','운동'].map(category=>({category,count:category==='공부'?count:0,level:category==='공부'&&count?1:0,color:'#f9a8d4'}));
  let fail=true, drinking=false;const posts=[];
  globalThis.fetch=async(url,options)=>{
    if(url==='/api/progress')return {ok:true,json:async()=>({progress:counts(0)})};
    assert.equal(url,'/api/keywords');posts.push(options.body);
    if(fail)return {ok:false,json:async()=>({detail:'분석에 실패했습니다.'})};
    if(drinking)return {ok:true,json:async()=>({keywords:['맥주'],summary:'술 기록',category:'술',category_keywords:['맥주'],needs_review:false,awarded:true,stack_changes:{'술':1,'운동':-1},progress:counts(1)})};
    return {ok:true,json:async()=>({keywords:['도서관','공부'],summary:'도서관에서 공부했다.',category:'공부',category_keywords:['공부'],needs_review:false,awarded:true,progress:counts(1)})};
  };
  await import('../static/app.js');
  await until(()=>!$('#open-post').disabled && $('#room-status').textContent.includes('1명'));
  assert.equal($('#home-panel').getAttribute('aria-hidden'),'false');
  const swipe=(name,x)=>{const event=new win.Event(name,{bubbles:true});Object.defineProperty(event,name==='touchstart'?'touches':'changedTouches',{value:[{clientX:x,clientY:150}]});$('#screen').dispatchEvent(event);};
  swipe('touchstart',30);swipe('touchend',180);assert.equal($('#screen').dataset.view,'lounge');
  swipe('touchstart',180);swipe('touchend',30);assert.equal($('#screen').dataset.view,'home');
  swipe('touchstart',180);swipe('touchend',30);assert.equal($('#screen').dataset.view,'feed');
  assert.equal($('#feed-panel').getAttribute('aria-hidden'),'false');
  swipe('touchstart',30);swipe('touchend',180);assert.equal($('#screen').dataset.view,'home');
  $('#lounge-tab').click();
  $('#open-friends').click();$('#friend-query').value='민지';$('#friend-search').dispatchEvent(new win.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>$('#search-results button'));$('#search-results button').click();
  await until(()=>$('#sent-invitations').textContent.includes('수락 대기'));
  assert.equal($('#room-members').children.length,1);
  assert.equal($('#search-results button').disabled,true);
  $('#close-friends').click();$('#open-demo').click();
  await until(()=>$('#demo-invitations button'));$('#demo-invitations button').click();
  await until(()=>$('#room-members').children.length===2);
  assert.ok($('#room-members').textContent.includes('민지'));
  const stored=JSON.parse(localStorage.getItem('campus-social-demo-v1'));
  assert.deepEqual(stored.rooms[0].member_ids,['user-1','user-2']);
  $('#close-demo').click();$('#open-inbox').click();await until(()=>$('#received-invitations button'));
  $('#received-invitations button').click();await until(()=>$('#room-select').options.length===2);
  assert.equal($('#room-select').value,'room-user-2');assert.equal($('#open-friends').disabled,true);
  $('#home-tab').click();$('#open-post').click();assert.ok($('#post-dialog').open);
  $('#post-form').dispatchEvent(new win.Event('submit',{bubbles:true,cancelable:true}));
  assert.ok($('#post-status').textContent.includes('하나 이상'));assert.equal(posts.length,0);
  $('#post-text').value='도서관에서 공부했다.';$('#post-text').dispatchEvent(new win.Event('input',{bubbles:true}));
  $('#post-form').dispatchEvent(new win.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>$('#post-status').textContent.includes('입력은 유지'));
  assert.equal($('#post-text').value,'도서관에서 공부했다.');assert.equal($('#post-fields').disabled,false);
  fail=false;$('#post-form').dispatchEvent(new win.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>!$('#post-result').hidden);
  assert.equal(posts[0].get('record_id'),posts[1].get('record_id'));
  assert.ok($('#result-effect').textContent.includes('1회'));assert.ok($('#activity-counts').textContent.includes('1회'));
  assert.ok($('#main-character .effect-공부'));
  $('#show-character').click();assert.equal($('#post-dialog').open,false);assert.equal($('#screen').dataset.view,'home');
  $('#open-post').click();assert.equal($('#post-text').value,'');assert.equal($('#post-result').hidden,true);
  const imageInput=$('#post-image');
  Object.defineProperty(imageInput,'files',{configurable:true,value:[new win.File(['img'],'photo.png',{type:'image/png'})]});
  imageInput.dispatchEvent(new win.Event('change'));
  assert.equal($('#preview-box').hidden,false);
  $('#post-form').dispatchEvent(new win.Event('submit',{bubbles:true,cancelable:true}));await until(()=>!$('#post-result').hidden);
  assert.equal(posts.at(-1).get('image').name,'photo.png');assert.equal(posts.at(-1).get('text'),'');
  $('#show-character').click();$('#open-post').click();drinking=true;
  $('#post-text').value='맥주를 마셨다.';$('#post-form').dispatchEvent(new win.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>!$('#post-result').hidden);
  assert.ok($('#result-effect').textContent.includes('운동 스택은 1 줄었어요'));
  assert.ok($('#global-status').textContent.includes('운동 −1'));
  dom.window.close();
});
